export function distance(a, b) {
  const r = Math.PI / 180,
    dLat = (b.lat - a.lat) * r,
    dLng = (b.lng - a.lng) * r;
  return (
    6371 *
    2 *
    Math.atan2(
      Math.sqrt(
        Math.sin(dLat / 2) ** 2 +
          Math.cos(a.lat * r) * Math.cos(b.lat * r) * Math.sin(dLng / 2) ** 2,
      ),
      Math.sqrt(
        1 -
          (Math.sin(dLat / 2) ** 2 +
            Math.cos(a.lat * r) *
              Math.cos(b.lat * r) *
              Math.sin(dLng / 2) ** 2),
      ),
    )
  );
}
export function estimate(plan) {
  const stays = plan.nights * plan.travelers * 3000,
    transport =
      { "Private cab": 5000, "Self-drive": 0, Tempo: 8000, Urbania: 12000 }[
        plan.transport
      ] || 0,
    crew =
      (plan.captain ? 2000 : 0) +
      (plan.photographer ? 3500 : 0) +
      (plan.marshal ? 3000 : 0);
  return { stays, transport, crew, total: stays + transport + crew };
}
